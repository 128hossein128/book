create table if not exists public.books (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 1 and 160),
  category text not null check (category in ('public', 'basij')),
  position integer not null,
  is_deleted boolean not null default false,
  deleted_at timestamptz null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists books_position_idx on public.books(position);
create index if not exists books_active_idx on public.books(is_deleted, position);

alter table public.books enable row level security;

