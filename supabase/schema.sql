create or replace function public.reorder_books(ordered_ids bigint[])
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.books as b
  set position = x.ord::integer,
      updated_at = now()
  from unnest(ordered_ids) with ordinality as x(id, ord)
  where b.id = x.id
    and b.is_deleted = false;
end;
$$;

revoke all on function public.reorder_books(bigint[]) from public, anon, authenticated;
grant execute on function public.reorder_books(bigint[]) to service_role;
